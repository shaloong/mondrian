//! Constants come from independent exact Fraction arithmetic, never the host.

use mondrian_core::ColorFrameAlpha;
use mondrian_effects::{
    blend_float_frames_in_place, over_float_sample, EffectAlphaConversionFailure,
    EffectColorDomain, EffectFloatFrame, EffectFloatFrameError, EffectFrameExtent,
    EffectValueFormat, EffectWorkingPrecision,
};

fn format(alpha: ColorFrameAlpha) -> EffectValueFormat {
    EffectValueFormat::new(
        EffectWorkingPrecision::Float32,
        EffectColorDomain::SceneLinearRgb,
        alpha,
    )
}

#[test]
fn complete_float_over_retains_third_exponent_below_overflow_midpoint() {
    let base = [0x6c11_8e00, 0x6c11_8e00, 0x6c11_8e00, 0x69e1_2000].map(f32::from_bits);
    let source = [0x8000_0001, 0x8000_0001, 0x8000_0001, 0x3f80_0001].map(f32::from_bits);
    let actual = over_float_sample(
        base,
        ColorFrameAlpha::StraightFloat,
        source,
        ColorFrameAlpha::PremultipliedFloat,
        f32::from_bits(0x3f7f_fffe),
    )
    .expect("the exact result is below the MAX/Infinity midpoint by a nonzero dyadic residual");
    assert_eq!(
        actual.map(f32::to_bits),
        [0x7f7f_ffff, 0x7f7f_ffff, 0x7f7f_ffff, 0x52e1_2000]
    );
}

#[test]
fn complete_float_frame_publishes_finite_three_exponent_cancellation() {
    let extent = EffectFrameExtent::new(1, 1);
    let mut base = EffectFloatFrame::from_pixels(
        extent,
        format(ColorFrameAlpha::StraightFloat),
        mondrian_core::ImageSampling::UNIT_SQUARE,
        vec![[0x6c11_8e00, 0x6c11_8e00, 0x6c11_8e00, 0x69e1_2000].map(f32::from_bits)],
    )
    .expect("finite base");
    let source = EffectFloatFrame::from_pixels(
        extent,
        format(ColorFrameAlpha::PremultipliedFloat),
        mondrian_core::ImageSampling::UNIT_SQUARE,
        vec![[0x8000_0001, 0x8000_0001, 0x8000_0001, 0x3f80_0001].map(f32::from_bits)],
    )
    .expect("finite source");
    blend_float_frames_in_place(
        &mut base,
        source.view(),
        f32::from_bits(0x3f7f_fffe),
        mondrian_core::types::BlendMode::Normal,
        0,
    )
    .expect("representable complete Float output must publish");
    assert_eq!(base.alpha(), ColorFrameAlpha::PremultipliedFloat);
    assert_eq!(
        base.pixels()[0].map(f32::to_bits),
        [0x7f7f_ffff, 0x7f7f_ffff, 0x7f7f_ffff, 0x52e1_2000]
    );
}

#[test]
fn complete_float_opaque_delivery_keeps_identical_color_at_extreme_signed_alpha() {
    let extent = EffectFrameExtent::new(1, 1);
    let color = [f32::MAX, -f32::MAX, f32::MAX];
    for alpha in [
        f32::MAX,
        -f32::MAX,
        f32::from_bits(0x5a80_0000),
        -f32::from_bits(0x5a80_0000),
    ] {
        for opacity in [0.0, 0.5, f32::from_bits(0x3f7f_ffff), 1.0] {
            let mut base = EffectFloatFrame::from_pixels(
                extent,
                format(ColorFrameAlpha::Opaque),
                mondrian_core::ImageSampling::UNIT_SQUARE,
                vec![[color[0], color[1], color[2], 1.0]],
            )
            .expect("finite opaque base");
            let source = EffectFloatFrame::from_pixels(
                extent,
                format(ColorFrameAlpha::StraightFloat),
                mondrian_core::ImageSampling::UNIT_SQUARE,
                vec![[color[0], color[1], color[2], alpha]],
            )
            .expect("finite extended alpha source");
            blend_float_frames_in_place(
                &mut base,
                source.view(),
                opacity,
                mondrian_core::types::BlendMode::Normal,
                0,
            )
            .expect("identical straight colors cancel exactly for every finite alpha");
            assert_eq!(base.alpha(), ColorFrameAlpha::Opaque);
            assert_eq!(
                base.pixels()[0].map(f32::to_bits),
                [0x7f7f_ffff, 0xff7f_ffff, 0x7f7f_ffff, 0x3f80_0000]
            );
        }
    }
}

#[test]
fn complete_float_frame_zero_opacity_preserves_original_signed_zero_bits() {
    let extent = EffectFrameExtent::new(1, 1);
    let original = [0x8000_0000, 0x0000_0000, 0x8000_0001, 0x8000_0000];
    let mut base = EffectFloatFrame::from_pixels(
        extent,
        format(ColorFrameAlpha::StraightFloat),
        mondrian_core::ImageSampling::UNIT_SQUARE,
        vec![original.map(f32::from_bits)],
    )
    .expect("finite base");
    let source = EffectFloatFrame::from_pixels(
        extent,
        format(ColorFrameAlpha::PremultipliedFloat),
        mondrian_core::ImageSampling::UNIT_SQUARE,
        vec![[7.0, -3.0, 11.0, 0.0]],
    )
    .expect("finite emission");
    blend_float_frames_in_place(
        &mut base,
        source.view(),
        0.0,
        mondrian_core::types::BlendMode::Normal,
        0,
    )
    .expect("identity frame delivery");
    assert_eq!(base.alpha(), ColorFrameAlpha::StraightFloat);
    assert_eq!(base.pixels()[0].map(f32::to_bits), original);
}

